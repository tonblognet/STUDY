import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import type { PrismaClient } from "@prisma/client";
import { createOpaqueToken, hashToken } from "../lib/auth/crypto";

/** Run inside the account HTTP suite's isolated schema and production server. */
export async function exerciseNotificationBacklog(
  db: PrismaClient,
  base: string,
) {
  const owner = await db.user.create({
    data: {
      email: `notification-backlog-${randomUUID()}@example.invalid`,
      emailVerified: new Date(),
    },
  });
  let cookie = "";
  const createSession = async () => {
    const token = createOpaqueToken();
    const user = await db.user.findUniqueOrThrow({ where: { id: owner.id } });
    await db.session.create({
      data: {
        userId: owner.id,
        tokenHash: token.tokenHash,
        authVersion: user.authVersion,
        expires: new Date(Date.now() + 3600000),
      },
    });
    cookie = `postupai_session=${token.token}`;
  };
  const request = (method = "GET", body?: unknown) =>
    fetch(`${base}/api/account/notifications`, {
      method,
      headers: {
        cookie,
        "x-account-id": owner.id,
        origin: base,
        "content-type": "application/json",
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
  const count = () =>
    db.notification.count({
      where: { userId: owner.id, type: "PERSONAL_DEADLINE" },
    });
  try {
    await createSession();
    const deadline = new Date(Date.now() - 3 * 86400000);
    deadline.setUTCMilliseconds(123);
    await db.accountTrackerItem.createMany({
      // Existing migrations preserve these over-limit owners even though new
      // POST/import paths only admit 200 records. Removed programs stay valid.
      data: Array.from({ length: 401 }, (_, index) => ({
        userId: owner.id,
        programKey:
          index === 1 ? "mai-applied-math" : `retired-fixture-${index}`,
        admissionYear: 2027,
        stage: "shortlist",
        deadlineAt: new Date(deadline.getTime() + index * 1000),
        history: [],
        notes: "private backlog fixture note",
      })),
    });
    const rows = await db.accountTrackerItem.findMany({
      where: { userId: owner.id },
      orderBy: { deadlineAt: "asc" },
      select: { id: true, programKey: true, deadlineAt: true },
    });
    const noticeId = (row: (typeof rows)[number]) =>
      hashToken(`${owner.id}:${row.id}:${row.deadlineAt!.toISOString()}`);
    await db.notification.create({
      // The new query must recognize IDs generated by the previous JS path.
      data: {
        id: noticeId(rows[0]),
        userId: owner.id,
        type: "PERSONAL_DEADLINE",
        title: "Legacy reminder",
        body: "Previously delivered fixture reminder",
      },
    });

    assert.equal((await request("PATCH", { enabled: false })).status, 200);
    const disabled = await request();
    assert.equal(disabled.status, 200);
    assert.equal((await disabled.json()).enabled, false);
    assert.equal(await count(), 1, "Disabled reminders must not drain backlog");
    assert.equal((await request("PATCH", { enabled: true })).status, 200);

    const first = await request();
    assert.equal(first.status, 200, await first.clone().text());
    const firstBody = await first.json();
    assert.equal(firstBody.enabled, true);
    assert.equal(firstBody.items.length, 100, "Visible history stays bounded");
    assert.equal(
      await count(),
      201,
      "A request creates at most 200 new notices",
    );

    await db.user.update({
      where: { id: owner.id },
      data: { authVersion: { increment: 1 } },
    });
    assert.equal((await request()).status, 401);
    assert.equal(
      await count(),
      201,
      "Revoked credentials cannot drain backlog",
    );
    await createSession();

    const second = await request();
    assert.equal(second.status, 200, await second.clone().text());
    assert.equal(
      await count(),
      401,
      "The next bounded request reaches remaining rows",
    );
    assert.equal((await request()).status, 200);
    assert.equal(
      await count(),
      401,
      "Repeated requests do not recreate notices",
    );

    const notifications = await db.notification.findMany({
      where: { userId: owner.id, type: "PERSONAL_DEADLINE" },
      select: { id: true, body: true },
    });
    assert.deepEqual(
      notifications.map((notice) => notice.id).sort(),
      rows.map(noticeId).sort(),
      "SQL UTC-millisecond hashes must match existing JS reminder IDs",
    );
    const legacyAlias = rows.find(
      (row) => row.programKey === "mai-applied-math",
    )!;
    assert.match(
      notifications.find((notice) => notice.id === noticeId(legacyAlias))!.body,
      /^МАИ · /,
      "Migrated slug keys retain their public program label",
    );
    assert.ok(
      notifications.every(
        (notice) => !notice.body.includes("private backlog fixture note"),
      ),
    );
  } finally {
    await db.auditLog.deleteMany({ where: { actorId: owner.id } });
    await db.user.delete({ where: { id: owner.id } });
  }
}
